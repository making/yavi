#!/bin/bash
set -e
n=16

for i in `seq 1 ${n}`;do
  class="Function${i}"
  if [ ${i} -eq 1 ];then args="one argument";else args="${i} arguments";fi
  file="$(dirname $0)/../src/main/java/am/ik/yavi/fn/${class}.java"
  echo $file
  cat <<EOF > ${file}
/*
 * SPDX-FileCopyrightText: 2018-2026 Toshiaki Maki <makingx@gmail.com>
 * SPDX-License-Identifier: Apache-2.0
 */
package am.ik.yavi.fn;

/**
 * A function that takes ${args} and produces a result.
 *
 * <p>
 * This is the ${i}-argument variant of {@link java.util.function.Function}, used to apply
 * a function to the values of combined validation results.
 *
 * <p>
 * An argument has the type that the validation declares for its value. A validation that
 * accepts {@code null} passes it on as it is, so an argument is {@code null} only if the
 * validation it comes from allows that, for example without {@code notNull()}.
 *
 * <p>
 * Generated by
 * <a href="https://github.com/making/yavi/blob/develop/scripts/generate-function.sh">generate-function.sh</a>.
 *
$(for j in `seq 1 ${i}`;do echo " * @param <T${j}> the type of argument ${j}";done)
 * @param <R> the type of the result
 * @since 0.6.0
 */
@FunctionalInterface
public interface ${class}<$(echo $(for j in `seq 1 ${i}`;do echo -n "T${j}, ";done) | sed 's/,$//'), R> {

	/**
	 * Applies this function to the given arguments.
$(for j in `seq 1 ${i}`;do echo "	 * @param t${j} argument ${j}";done)
	 * @return the function result
	 */
	R apply($(echo $(for j in `seq 1 ${i}`;do echo -n "T${j} t${j}, ";done) | sed 's/,$//'));
}
EOF
done