package am.ik.yavi;

public class Message {

	private final String text;

	private final Color color;

	public Message(String text, Color color) {
		this.text = text;
		this.color = color;
	}

	public String getText() {
		return text;
	}

	public Color getColor() {
		return color;
	}

}
