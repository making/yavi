	/**
	 * Combines the given validation results into a validation result holding the list of
	 * their values in iteration order.
	 *
	 * <p>
	 * All validation results are inspected; if any of them fails, the errors of all
	 * failed validations are accumulated in iteration order and returned as a failure. An
	 * empty iterable yields a success holding an empty list.
	 * @param validations the validation results to combine
	 * @param <E> the type of the errors of the validation results
	 * @param <T> the type of the values of the validation results
	 * @return a successful validation holding the list of values or a failure holding the
	 * accumulated errors
	 */
	public static <E, T> Validation<E, List<T>> sequence(
			Iterable<? extends Validation<? extends E, ? extends T>> validations) {
		return traverse(validations, identity());
	}

	/**
	 * Maps each value with the given function to a validation result and combines the
	 * results into a validation result holding the list of their values in iteration
	 * order.
	 *
	 * <p>
	 * The function is invoked for every value, even after a validation failed. If any
	 * produced validation fails, the errors of all failed validations are accumulated in
	 * iteration order and returned as a failure.
	 * @param values the values to validate
	 * @param mapper function that validates each value
	 * @param <E> the type of the errors of the produced validations
	 * @param <T> the type of the input values
	 * @param <U> the type of the validated values
	 * @return a successful validation holding the list of values or a failure holding the
	 * accumulated errors
	 */
	public static <E, T, U> Validation<E, List<U>> traverse(Iterable<T> values,
			Function<? super T, ? extends Validation<? extends E, ? extends U>> mapper) {
		return traverseIndexed(values, IndexedTraverser.ignoreIndex(mapper));
	}

	/**
	 * A traverser that receives a value and its position in the iteration.
	 *
	 * @param <A> the type of the value
	 * @param <R> the type of the result
	 * @since 0.7.0
	 */
	@FunctionalInterface
	public interface IndexedTraverser<A, R> {

		/**
		 * Applies this traverser to the given value and index.
		 * @param a the value
		 * @param index the position of the value
		 * @return the traversal result
		 */
		R apply(A a, int index);

		/**
		 * Returns a traverser that ignores the index and delegates to the given function.
		 * @param f the function applied to the value
		 * @param <A> the type of the value
		 * @param <R> the type of the result
		 * @return a traverser that ignores the index
		 */
		static <A, R> IndexedTraverser<A, R> ignoreIndex(Function<? super A, ? extends R> f) {
			return (a, index) -> f.apply(a);
		}

	}

	/**
	 * Maps each value with the given traverser to a validation result and combines the
	 * results into a validation result holding the list of their values in iteration
	 * order.
	 *
	 * <p>
	 * The traverser is invoked for every value with its position, even after a validation
	 * failed. If any produced validation fails, the errors of all failed validations are
	 * accumulated in iteration order and returned as a failure.
	 * @param values the values to validate
	 * @param traverser traverser that validates each value and its index
	 * @param <E> the type of the errors of the produced validations
	 * @param <T> the type of the input values
	 * @param <U> the type of the validated values
	 * @return a successful validation holding the list of values or a failure holding the
	 * accumulated errors
	 * @since 0.7.0
	 */
	public static <E, T, U> Validation<E, List<U>> traverseIndexed(@Nullable Iterable<T> values,
			IndexedTraverser<? super T, ? extends Validation<? extends E, ? extends U>> traverser) {
		return traverseIndexed(values, traverser, ArrayList::new);
	}

	/**
	 * Maps each value with the given traverser to a validation result and collects the
	 * results into a collection created by the given factory.
	 *
	 * <p>
	 * The factory is invoked once before the iteration. The traverser is invoked for
	 * every value with its position, even after a validation failed. The collection is
	 * returned only if all produced validations succeed; otherwise the errors of all
	 * failed validations are accumulated in iteration order and returned as a failure.
	 * @param values the values to validate
	 * @param traverser traverser that validates each value and its index
	 * @param factory supplier of the collection that receives the validated values
	 * @param <E> the type of the errors of the produced validations
	 * @param <T> the type of the input values
	 * @param <U> the type of the validated values
	 * @param <C> the type of the resulting collection
	 * @return a successful validation holding the collection of values or a failure
	 * holding the accumulated errors
	 * @since 0.8.0
	 */
	public static <E, T, U, C extends Collection<U>> Validation<E, C> traverseIndexed(@Nullable Iterable<T> values,
			IndexedTraverser<? super T, ? extends Validation<? extends E, ? extends U>> traverser,
			Supplier<C> factory) {
		if (values == null) {
			return Validation.success(factory.get());
		}
		final List<E> errors = new ArrayList<>();
		final C results = factory.get();
		int index = 0;
		for (T value : values) {
			traverser.apply(value, index++).fold(errors::addAll, results::add);
		}
		return errors.isEmpty() ? Validation.success(results) : Validation.failure(errors);
	}

	/**
	 * Validates the value contained in the given optional, if any, and returns a
	 * validation result holding an optional with the produced value.
	 *
	 * <p>
	 * An empty optional yields a success holding {@link Optional#empty()}; the function
	 * is not invoked in that case. If the function produces a failure, its errors are
	 * returned.
	 * @param value the optional value to validate
	 * @param mapper function that validates the contained value
	 * @param <E> the type of the errors of the produced validation
	 * @param <T> the contained type of the optional
	 * @param <U> the type of the produced value
	 * @return a successful validation holding the optional value or a failure holding the
	 * errors
	 * @since 0.8.0
	 */
	@SuppressWarnings("unchecked")
	public static <E, T, U> Validation<E, Optional<U>> traverseOptional(@Nullable Optional<T> value,
			Function<? super T, ? extends Validation<? extends E, ? extends U>> mapper) {
		if (value == null) {
			return Validation.success(Optional.empty());
		}
		return value.map(t -> mapper.apply(t).bimap(es -> (List<E>) es, u -> Optional.of((U) u))) //
			.orElse(Validation.success(Optional.empty()));
	}

