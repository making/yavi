package am.ik.yavi.fn;

import org.jspecify.annotations.Nullable;

/**
 * A function that takes 3 arguments and produces a result.
 *
 * <p>
 * This is the 3-argument variant of {@link java.util.function.Function}, used to apply a
 * function to the values of combined validation results.
 *
 * <p>
 * An argument has the type that the validation declares for its value, so it is
 * {@code null} only if that type is nullable, for example after {@code nullable()}.
 *
 * <p>
 * Generated by <a href=
 * "https://github.com/making/yavi/blob/develop/scripts/generate-function.sh">generate-function.sh</a>.
 *
 * @param <T1> the type of argument 1
 * @param <T2> the type of argument 2
 * @param <T3> the type of argument 3
 * @param <R> the type of the result
 * @since 0.6.0
 */
@FunctionalInterface
public interface Function3<T1 extends @Nullable Object, T2 extends @Nullable Object, T3 extends @Nullable Object, R extends @Nullable Object> {

	/**
	 * Applies this function to the given arguments.
	 * @param t1 argument 1
	 * @param t2 argument 2
	 * @param t3 argument 3
	 * @return the function result
	 */
	R apply(T1 t1, T2 t2, T3 t3);

}
