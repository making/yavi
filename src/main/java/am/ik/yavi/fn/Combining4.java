package am.ik.yavi.fn;

/**
 * Combines validation results and applies a function to their values in applicative
 * style.
 *
 * <p>
 * If any of the combined validations fails, the errors of all failed validations are
 * accumulated in the order of the combined validations and no value is produced. If all
 * of them succeed, the function receives their values and its result is returned as a
 * success. Use {@link Validations#combine} or chain {@link Validation#combine} to create
 * an instance and {@link #apply(Function4)} to apply the function.
 *
 * <p>
 * Generated by <a href=
 * "https://github.com/making/yavi/blob/develop/scripts/generate-applicative.sh">generate-applicative.sh</a>.
 *
 * @param <E> the type of the errors of the combined validations
 * @param <T1> the value type of validation 1
 * @param <T2> the value type of validation 2
 * @param <T3> the value type of validation 3
 * @param <T4> the value type of validation 4
 * @since 0.6.0
 */
public class Combining4<E, T1, T2, T3, T4> {

	/**
	 * The validation at position 1 of this combination.
	 */
	protected final Validation<E, T1> v1;

	/**
	 * The validation at position 2 of this combination.
	 */
	protected final Validation<E, T2> v2;

	/**
	 * The validation at position 3 of this combination.
	 */
	protected final Validation<E, T3> v3;

	/**
	 * The validation at position 4 of this combination.
	 */
	protected final Validation<E, T4> v4;

	/**
	 * Creates a combination of the given validations.
	 * @param v1 validation 1
	 * @param v2 validation 2
	 * @param v3 validation 3
	 * @param v4 validation 4
	 */
	public Combining4(Validation<E, T1> v1, Validation<E, T2> v2, Validation<E, T3> v3, Validation<E, T4> v4) {
		this.v1 = v1;
		this.v2 = v2;
		this.v3 = v3;
		this.v4 = v4;
	}

	/**
	 * Applies the given function to the values of the combined validations if all of them
	 * are successful.
	 *
	 * <p>
	 * The validations are evaluated in order. If any of them fails, the errors of all
	 * failed validations are accumulated in the order of the combined validations and
	 * returned as a failure; the function is not invoked.
	 * @param f the function that receives the validated values
	 * @param <R> the type of the result
	 * @param <V> the concrete validation type returned
	 * @return the successful result of the function or the accumulated errors
	 */
	public <R, V extends Validation<E, R>> V apply(Function4<T1, T2, T3, T4, R> f) {
		final Validation<E, Function1<T2, Function1<T3, Function1<T4, R>>>> apply1 = v1
			.apply(Validation.success(Functions.curry(f)));
		final Validation<E, Function1<T3, Function1<T4, R>>> apply2 = v2.apply(apply1);
		final Validation<E, Function1<T4, R>> apply3 = v3.apply(apply2);
		return v4.apply(apply3);
	}

	/**
	 * Returns a combination that also includes the given validation. The validation is
	 * appended after the existing ones, which determines the order of accumulated errors.
	 * @param v5 the validation to add
	 * @param <T5> the value type of the added validation
	 * @return the combination of 5 validations
	 */
	public <T5> Combining5<E, T1, T2, T3, T4, T5> combine(Validation<E, T5> v5) {
		return new Combining5<>(v1, v2, v3, v4, v5);
	}

}
