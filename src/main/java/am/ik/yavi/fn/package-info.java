/**
 * Functional primitives for applicative validation.
 *
 * <p>
 * {@link am.ik.yavi.fn.Validation} is a result type that either holds a success value or
 * accumulates errors, similar to Vavr's {@code Validation}. Unlike an exception based
 * flow, combining several validation results does not stop at the first error:
 * {@link am.ik.yavi.fn.Validations#combine} and {@link am.ik.yavi.fn.Validations#apply}
 * build a {@link am.ik.yavi.fn.Combining2 combination} of up to 16 validations whose
 * {@code apply} method accumulates the errors of all failed validations.
 *
 * <p>
 * {@link am.ik.yavi.fn.Function1} to {@link am.ik.yavi.fn.Function16} are functional
 * interfaces for that arity, and {@link am.ik.yavi.fn.Functions#curry} converts them into
 * curried form so that a validation can be applied step by step.
 * {@link am.ik.yavi.fn.Pair} is a simple immutable pair type.
 *
 * <p>
 * Application code normally uses the specialized counterparts in {@code am.ik.yavi.core}
 * ({@link am.ik.yavi.core.Validated}, {@link am.ik.yavi.core.ValueValidator}) and the
 * generated {@code am.ik.yavi.arguments.ArgumentsNValidator} types, which build on this
 * package. {@code FunctionN} and {@code CombiningN} are generated by the scripts in
 * {@code scripts/}; do not edit them directly.
 */
@NonNullApi
package am.ik.yavi.fn;

