package am.ik.yavi.fn;

/**
 * A function that takes one argument and produces a result.
 *
 * <p>
 * This is the 1-argument variant of {@link java.util.function.Function}, used to apply a
 * function to the values of combined validation results.
 *
 * <p>
 * An argument has the type that the validation declares for its value. A validation that
 * accepts {@code null} passes it on as it is, so an argument is {@code null} only if the
 * validation it comes from allows that, for example without {@code notNull()}.
 *
 * <p>
 * Generated by <a href=
 * "https://github.com/making/yavi/blob/develop/scripts/generate-function.sh">generate-function.sh</a>.
 *
 * @param <T1> the type of argument 1
 * @param <R> the type of the result
 * @since 0.6.0
 */
@FunctionalInterface
public interface Function1<T1, R> {

	/**
	 * Applies this function to the given arguments.
	 * @param t1 argument 1
	 * @return the function result
	 */
	R apply(T1 t1);

}
