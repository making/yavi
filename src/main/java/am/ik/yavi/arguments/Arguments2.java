package am.ik.yavi.arguments;

import java.util.Objects;

import am.ik.yavi.fn.Function2;
import org.jspecify.annotations.Nullable;

/**
 * An immutable container of 2 arguments.
 *
 * <p>
 * Instances are created with {@link Arguments#of}. The {@code wrap()} and
 * {@code unwrap(...)} methods of {@link Arguments2Validator} convert between validating
 * the arguments individually and validating this container as a single value. This class
 * only stores, compares and maps the argument values; it performs no validation, and an
 * argument may be {@code null}.
 *
 * <p>
 * The {@code first*}, {@code last*}, {@code append}, {@code prepend} and {@code reverse}
 * methods derive another container from the same argument values. Equality and the hash
 * code are based on the argument values and the concrete class.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @since 0.3.0
 */
public final class Arguments2<A1, A2> {

	private final @Nullable A1 arg1;

	private final @Nullable A2 arg2;

	/**
	 * Creates a container with the given arguments. The arguments may be {@code null} and
	 * are stored as is.
	 * @param arg1 the argument at position 1, arg2 the argument at position 2
	 */
	Arguments2(@Nullable A1 arg1, @Nullable A2 arg2) {
		this.arg1 = arg1;
		this.arg2 = arg2;
	}

	/**
	 * Returns the argument at position 1, which may be {@code null}.
	 * @return the argument at position 1, possibly {@code null}
	 */
	@Nullable public A1 arg1() {
		return this.arg1;
	}

	/**
	 * Returns the argument at position 2, which may be {@code null}.
	 * @return the argument at position 2, possibly {@code null}
	 */
	@Nullable public A2 arg2() {
		return this.arg2;
	}

	/**
	 * Applies the given function to every argument contained in this container and
	 * returns its result.
	 *
	 * <p>
	 * No validation is performed and the arguments are passed as they are, possibly
	 * {@code null}.
	 * @param <X> the type of the result
	 * @param mapper the function to apply to the arguments
	 * @return the result of applying the mapper function to the arguments
	 */
	public <X> X map(Function2<? super A1, ? super A2, ? extends X> mapper) {
		return mapper.apply(arg1, arg2);
	}

	/**
	 * Returns a new {@link Arguments1} containing the arguments at positions 1 to 1 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments1 instance with arguments from arg1 to arg1
	 * @since 0.16.0
	 */
	public Arguments1<A1> first1() {
		return new Arguments1<>(arg1);
	}

	/**
	 * Returns a new {@link Arguments1} containing the arguments at positions 2 to 2 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments1 instance with arguments from arg2 to arg2
	 * @since 0.16.0
	 */
	public Arguments1<A2> last1() {
		return new Arguments1<>(arg2);
	}

	/**
	 * Returns a new {@link Arguments3} with the given argument appended after the
	 * existing arguments.
	 *
	 * <p>
	 * The existing argument values are copied by reference; no validation is performed.
	 * @param <B> the type of the argument to append
	 * @param arg the argument to append, possibly {@code null}
	 * @return a new Arguments3 instance with the additional argument
	 * @since 0.16.0
	 */
	public <B> Arguments3<A1, A2, B> append(@Nullable B arg) {
		return new Arguments3<>(this.arg1, this.arg2, arg);
	}

	/**
	 * Returns a new {@link Arguments3} with the given argument prepended before the
	 * existing arguments.
	 *
	 * <p>
	 * The existing argument values are copied by reference; no validation is performed.
	 * @param <B> the type of the argument to prepend
	 * @param arg the argument to prepend, possibly {@code null}
	 * @return a new Arguments3 instance with the additional argument
	 * @since 0.16.0
	 */
	public <B> Arguments3<B, A1, A2> prepend(@Nullable B arg) {
		return new Arguments3<>(arg, this.arg1, this.arg2);
	}

	/**
	 * Returns a new {@link Arguments2} with the arguments in reverse order.
	 *
	 * <p>
	 * The argument values are copied by reference; no validation is performed.
	 * @return an Arguments2 instance with arguments in reverse order
	 * @since 0.16.0
	 */
	public Arguments2<A2, A1> reverse() {
		return new Arguments2<>(arg2, arg1);
	}

	/**
	 * Returns whether the given object is an {@code Arguments2} with equal argument
	 * values. Two containers are equal only if they have the same concrete class and
	 * every argument is equal, using {@link java.util.Objects#equals(Object, Object)}.
	 * @param obj the reference object with which to compare
	 * @return true if the given object holds equal argument values; false otherwise
	 */
	@Override
	@SuppressWarnings("unchecked")
	public boolean equals(@Nullable Object obj) {
		if (this == obj) {
			return true;
		}
		if (obj == null || getClass() != obj.getClass()) {
			return false;
		}
		Arguments2<A1, A2> that = (Arguments2<A1, A2>) obj;
		return Objects.equals(this.arg1, that.arg1) && Objects.equals(this.arg2, that.arg2);
	}

	/**
	 * Returns a hash code consistent with {@link #equals(Object)}, computed from all
	 * argument values.
	 * @return a hash code value for this object
	 */
	@Override
	public int hashCode() {
		return Objects.hash(this.arg1, this.arg2);
	}

	/**
	 * Returns a string representation of this container including all argument values.
	 * @return a string representation of this object
	 */
	@Override
	public String toString() {
		return "Arguments2{" + "arg1=" + this.arg1 + ", " + "arg2=" + this.arg2 + "}";
	}

}
