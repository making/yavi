package am.ik.yavi.arguments;

import java.util.Locale;
import java.util.function.Supplier;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.Validated;
import am.ik.yavi.core.ValueDescription;
import am.ik.yavi.core.ValueValidator;
import am.ik.yavi.fn.Function12;
import am.ik.yavi.fn.Validations;
import org.jspecify.annotations.Nullable;

/**
 * Combines 12 validators that validate distinct arguments into a validator for those
 * arguments.
 *
 * <p>
 * Each argument is validated with its own {@link ValueValidator}. The validators are
 * applied independently: all violations are accumulated, and the function passed to
 * {@link #apply} is applied only when every validation succeeds. Instances are created
 * with {@link ArgumentsValidators#split} or by chaining {@code split} on an existing
 * instance.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <A3> the type of the argument at position 3
 * @param <A4> the type of the argument at position 4
 * @param <A5> the type of the argument at position 5
 * @param <A6> the type of the argument at position 6
 * @param <A7> the type of the argument at position 7
 * @param <A8> the type of the argument at position 8
 * @param <A9> the type of the argument at position 9
 * @param <A10> the type of the argument at position 10
 * @param <A11> the type of the argument at position 11
 * @param <A12> the type of the argument at position 12
 * @param <R1> the type of the value produced for the argument at position 1
 * @param <R2> the type of the value produced for the argument at position 2
 * @param <R3> the type of the value produced for the argument at position 3
 * @param <R4> the type of the value produced for the argument at position 4
 * @param <R5> the type of the value produced for the argument at position 5
 * @param <R6> the type of the value produced for the argument at position 6
 * @param <R7> the type of the value produced for the argument at position 7
 * @param <R8> the type of the value produced for the argument at position 8
 * @param <R9> the type of the value produced for the argument at position 9
 * @param <R10> the type of the value produced for the argument at position 10
 * @param <R11> the type of the value produced for the argument at position 11
 * @param <R12> the type of the value produced for the argument at position 12
 * @since 0.7.0
 */
public class Arguments12Splitting<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, R1, R2, R3, R4, R5, R6, R7, R8, R9, R10, R11, R12> {

	/** The validator applied to the argument at position 1. */
	protected final ValueValidator<? super A1, ? extends R1> v1;

	/** The validator applied to the argument at position 2. */
	protected final ValueValidator<? super A2, ? extends R2> v2;

	/** The validator applied to the argument at position 3. */
	protected final ValueValidator<? super A3, ? extends R3> v3;

	/** The validator applied to the argument at position 4. */
	protected final ValueValidator<? super A4, ? extends R4> v4;

	/** The validator applied to the argument at position 5. */
	protected final ValueValidator<? super A5, ? extends R5> v5;

	/** The validator applied to the argument at position 6. */
	protected final ValueValidator<? super A6, ? extends R6> v6;

	/** The validator applied to the argument at position 7. */
	protected final ValueValidator<? super A7, ? extends R7> v7;

	/** The validator applied to the argument at position 8. */
	protected final ValueValidator<? super A8, ? extends R8> v8;

	/** The validator applied to the argument at position 9. */
	protected final ValueValidator<? super A9, ? extends R9> v9;

	/** The validator applied to the argument at position 10. */
	protected final ValueValidator<? super A10, ? extends R10> v10;

	/** The validator applied to the argument at position 11. */
	protected final ValueValidator<? super A11, ? extends R11> v11;

	/** The validator applied to the argument at position 12. */
	protected final ValueValidator<? super A12, ? extends R12> v12;

	/**
	 * Creates an instance with the given validators, one per argument.
	 * @param v1 the validator applied to the argument at position 1
	 * @param v2 the validator applied to the argument at position 2
	 * @param v3 the validator applied to the argument at position 3
	 * @param v4 the validator applied to the argument at position 4
	 * @param v5 the validator applied to the argument at position 5
	 * @param v6 the validator applied to the argument at position 6
	 * @param v7 the validator applied to the argument at position 7
	 * @param v8 the validator applied to the argument at position 8
	 * @param v9 the validator applied to the argument at position 9
	 * @param v10 the validator applied to the argument at position 10
	 * @param v11 the validator applied to the argument at position 11
	 * @param v12 the validator applied to the argument at position 12
	 */
	public Arguments12Splitting(ValueValidator<? super A1, ? extends R1> v1,
			ValueValidator<? super A2, ? extends R2> v2, ValueValidator<? super A3, ? extends R3> v3,
			ValueValidator<? super A4, ? extends R4> v4, ValueValidator<? super A5, ? extends R5> v5,
			ValueValidator<? super A6, ? extends R6> v6, ValueValidator<? super A7, ? extends R7> v7,
			ValueValidator<? super A8, ? extends R8> v8, ValueValidator<? super A9, ? extends R9> v9,
			ValueValidator<? super A10, ? extends R10> v10, ValueValidator<? super A11, ? extends R11> v11,
			ValueValidator<? super A12, ? extends R12> v12) {
		this.v1 = v1;
		this.v2 = v2;
		this.v3 = v3;
		this.v4 = v4;
		this.v5 = v5;
		this.v6 = v6;
		this.v7 = v7;
		this.v8 = v8;
		this.v9 = v9;
		this.v10 = v10;
		this.v11 = v11;
		this.v12 = v12;
	}

	/**
	 * Returns a validator that applies the validators of this instance to the arguments
	 * and combines the validated values with the given function.
	 *
	 * <p>
	 * All violations are accumulated and the function is applied only when every
	 * validation succeeds. The validator describes its arguments as
	 * {@link ValueDescription.Properties} with one property per argument, named as
	 * {@link ValueDescription.Properties#ofArguments} states.
	 * @param f the function that combines the validated values
	 * @param <X> the type of the value produced by the function
	 * @return a validator for the 12 arguments
	 */
	public <X> Arguments12Validator<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, X> apply(
			Function12<? super R1, ? super R2, ? super R3, ? super R4, ? super R5, ? super R6, ? super R7, ? super R8, ? super R9, ? super R10, ? super R11, ? super R12, ? extends X> f) {
		return new Arguments12Validator<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, X>() {

			@Override
			public Arguments12Validator<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, Supplier<X>> lazy() {
				return ((a1, a2, a3, a4, a5, a6, a7, a8, a9, a10, a11, a12, locale,
						constraintContext) -> Validations.apply(
								(r1, r2, r3, r4, r5, r6, r7, r8, r9, r10, r11,
										r12) -> () -> f.apply(r1, r2, r3, r4, r5, r6, r7, r8, r9, r10, r11, r12),
								v1.validate(a1, locale, constraintContext), v2.validate(a2, locale, constraintContext),
								v3.validate(a3, locale, constraintContext), v4.validate(a4, locale, constraintContext),
								v5.validate(a5, locale, constraintContext), v6.validate(a6, locale, constraintContext),
								v7.validate(a7, locale, constraintContext), v8.validate(a8, locale, constraintContext),
								v9.validate(a9, locale, constraintContext),
								v10.validate(a10, locale, constraintContext),
								v11.validate(a11, locale, constraintContext),
								v12.validate(a12, locale, constraintContext)));
			}

			@Override
			public Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, @Nullable A4 a4,
					@Nullable A5 a5, @Nullable A6 a6, @Nullable A7 a7, @Nullable A8 a8, @Nullable A9 a9,
					@Nullable A10 a10, @Nullable A11 a11, @Nullable A12 a12, Locale locale,
					ConstraintContext constraintContext) {
				return Validations.apply(f::apply, v1.validate(a1, locale, constraintContext),
						v2.validate(a2, locale, constraintContext), v3.validate(a3, locale, constraintContext),
						v4.validate(a4, locale, constraintContext), v5.validate(a5, locale, constraintContext),
						v6.validate(a6, locale, constraintContext), v7.validate(a7, locale, constraintContext),
						v8.validate(a8, locale, constraintContext), v9.validate(a9, locale, constraintContext),
						v10.validate(a10, locale, constraintContext), v11.validate(a11, locale, constraintContext),
						v12.validate(a12, locale, constraintContext));
			}

			@Override
			public ValueDescription description() {
				return ValueDescription.Properties.ofArguments(v1.description(), v2.description(), v3.description(),
						v4.description(), v5.description(), v6.description(), v7.description(), v8.description(),
						v9.description(), v10.description(), v11.description(), v12.description());
			}
		};
	}

	/**
	 * Returns a new {@link Arguments13Splitting} that additionally validates the argument
	 * at position 13 with the given validator.
	 * @param v13 the validator applied to the argument at position 13
	 * @param <A13> the type of the argument at position 13
	 * @param <R13> the type of the value produced for the argument at position 13
	 * @return an arguments13 splitting instance
	 */
	public <A13, R13> Arguments13Splitting<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, A13, R1, R2, R3, R4, R5, R6, R7, R8, R9, R10, R11, R12, R13> split(
			ValueValidator<? super A13, ? extends R13> v13) {
		return new Arguments13Splitting<>(v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12, v13);
	}

}
