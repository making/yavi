package am.ik.yavi.arguments;

import am.ik.yavi.core.ValidatedCombining6;
import am.ik.yavi.core.ValueDescription;
import am.ik.yavi.core.ValueValidator;
import am.ik.yavi.fn.Function6;
import org.jspecify.annotations.Nullable;

/**
 * Combines 6 validators that validate distinct arguments into a validator for those
 * arguments.
 *
 * <p>
 * Each argument is validated with its own {@link ValueValidator}. The validators are
 * applied independently: all violations are accumulated, and the function passed to
 * {@link #apply} is applied only when every validation succeeds. Instances are created
 * with {@link ArgumentsValidators#split} or by chaining {@code split} on an existing
 * instance.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <A3> the type of the argument at position 3
 * @param <A4> the type of the argument at position 4
 * @param <A5> the type of the argument at position 5
 * @param <A6> the type of the argument at position 6
 * @param <R1> the type of the value produced for the argument at position 1
 * @param <R2> the type of the value produced for the argument at position 2
 * @param <R3> the type of the value produced for the argument at position 3
 * @param <R4> the type of the value produced for the argument at position 4
 * @param <R5> the type of the value produced for the argument at position 5
 * @param <R6> the type of the value produced for the argument at position 6
 * @since 0.7.0
 */
public class Arguments6Splitting<A1, A2, A3, A4, A5, A6, R1 extends @Nullable Object, R2 extends @Nullable Object, R3 extends @Nullable Object, R4 extends @Nullable Object, R5 extends @Nullable Object, R6 extends @Nullable Object> {

	/** The validator applied to the argument at position 1. */
	protected final ValueValidator<? super A1, ? extends R1> v1;

	/** The validator applied to the argument at position 2. */
	protected final ValueValidator<? super A2, ? extends R2> v2;

	/** The validator applied to the argument at position 3. */
	protected final ValueValidator<? super A3, ? extends R3> v3;

	/** The validator applied to the argument at position 4. */
	protected final ValueValidator<? super A4, ? extends R4> v4;

	/** The validator applied to the argument at position 5. */
	protected final ValueValidator<? super A5, ? extends R5> v5;

	/** The validator applied to the argument at position 6. */
	protected final ValueValidator<? super A6, ? extends R6> v6;

	/**
	 * Creates an instance with the given validators, one per argument.
	 * @param v1 the validator applied to the argument at position 1
	 * @param v2 the validator applied to the argument at position 2
	 * @param v3 the validator applied to the argument at position 3
	 * @param v4 the validator applied to the argument at position 4
	 * @param v5 the validator applied to the argument at position 5
	 * @param v6 the validator applied to the argument at position 6
	 */
	public Arguments6Splitting(ValueValidator<? super A1, ? extends R1> v1, ValueValidator<? super A2, ? extends R2> v2,
			ValueValidator<? super A3, ? extends R3> v3, ValueValidator<? super A4, ? extends R4> v4,
			ValueValidator<? super A5, ? extends R5> v5, ValueValidator<? super A6, ? extends R6> v6) {
		this.v1 = v1;
		this.v2 = v2;
		this.v3 = v3;
		this.v4 = v4;
		this.v5 = v5;
		this.v6 = v6;
	}

	/**
	 * Returns a validator that applies the validators of this instance to the arguments
	 * and combines the validated values with the given function.
	 *
	 * <p>
	 * All violations are accumulated and the function is applied only when every
	 * validation succeeds. The validator describes its arguments as
	 * {@link ValueDescription.Properties} with one property per argument, named as
	 * {@link ValueDescription.Properties#ofArguments} states.
	 * @param f the function that combines the validated values
	 * @param <X> the type of the value produced by the function
	 * @return a validator for the 6 arguments
	 */
	public <X extends @Nullable Object> Arguments6Validator<A1, A2, A3, A4, A5, A6, X> apply(
			Function6<? super R1, ? super R2, ? super R3, ? super R4, ? super R5, ? super R6, ? extends X> f) {
		return ArgumentsValidators.derived(
				(a1, a2, a3, a4, a5, a6, locale,
						constraintContext) -> new ValidatedCombining6<>(v1.validate(a1, locale, constraintContext),
								v2.validate(a2, locale, constraintContext), v3.validate(a3, locale, constraintContext),
								v4.validate(a4, locale, constraintContext), v5.validate(a5, locale, constraintContext),
								v6.validate(a6, locale, constraintContext))
							.apply(f::apply),
				() -> (a1, a2, a3, a4, a5, a6, locale,
						constraintContext) -> new ValidatedCombining6<>(v1.validate(a1, locale, constraintContext),
								v2.validate(a2, locale, constraintContext), v3.validate(a3, locale, constraintContext),
								v4.validate(a4, locale, constraintContext), v5.validate(a5, locale, constraintContext),
								v6.validate(a6, locale, constraintContext))
							.apply((r1, r2, r3, r4, r5, r6) -> () -> f.apply(r1, r2, r3, r4, r5, r6)),
				() -> ValueDescription.Properties.ofArguments(v1.description(), v2.description(), v3.description(),
						v4.description(), v5.description(), v6.description()));
	}

	/**
	 * Returns a new {@link Arguments7Splitting} that additionally validates the argument
	 * at position 7 with the given validator.
	 * @param v7 the validator applied to the argument at position 7
	 * @param <A7> the type of the argument at position 7
	 * @param <R7> the type of the value produced for the argument at position 7
	 * @return an arguments7 splitting instance
	 */
	public <A7, R7 extends @Nullable Object> Arguments7Splitting<A1, A2, A3, A4, A5, A6, A7, R1, R2, R3, R4, R5, R6, R7> split(
			ValueValidator<? super A7, ? extends R7> v7) {
		return new Arguments7Splitting<>(v1, v2, v3, v4, v5, v6, v7);
	}

}
