package am.ik.yavi.arguments;

import java.util.Locale;
import java.util.Objects;
import java.util.function.Function;
import java.util.function.Predicate;
import java.util.function.Supplier;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.ConstraintGroup;
import am.ik.yavi.core.ConstraintViolationsException;
import am.ik.yavi.core.Validated;
import am.ik.yavi.core.ValueDescription;
import am.ik.yavi.core.ValueValidator;
import am.ik.yavi.core.ViolationMessage;
import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;

/**
 * Validates 3 arguments and produces a value of type {@code X}.
 *
 * <p>
 * Validation is applicative: all violations are accumulated in the returned
 * {@link Validated} instead of stopping at the first one, and a value is produced only
 * when every constraint succeeds. Whether a {@code null} argument is accepted depends on
 * how the validator is built: an argument added to the builders of {@code Yavi.schema()}
 * is required unless it is made {@code nullable()} or {@code optional()}, and a validator
 * built with {@link am.ik.yavi.builder.ArgumentsValidatorBuilder} accepts {@code null}
 * unless a configured constraint rejects it (for example {@code notNull()}); see
 * {@link am.ik.yavi.core.NullAs}.
 *
 * <p>
 * Instances are usually created with
 * {@link am.ik.yavi.builder.ArgumentsValidatorBuilder#of} or a typed builder, and with
 * the factories of {@link ArgumentsValidators}. The default methods adapt the input type
 * with {@link #compose}, transform the validated value with {@link #map}, and add more
 * validators through the splitting and combining factories.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <A3> the type of the argument at position 3
 * @param <X> the type of the value produced when validation succeeds
 * @since 0.3.0
 */
@FunctionalInterface
public interface Arguments3Validator<A1, A2, A3, X extends @Nullable Object> {

	/**
	 * Returns an {@link Arguments3Validator} that takes the arguments directly instead of
	 * an {@link Arguments3} container.
	 *
	 * <p>
	 * The returned validator wraps the arguments with {@link Arguments#of} before
	 * delegating to the given validator.
	 * @param validator a validator for {@code Arguments3} and its argument types
	 * @param <A1> the type of the argument at position 1
	 * @param <A2> the type of the argument at position 2
	 * @param <A3> the type of the argument at position 3
	 * @param <X> the type of the value produced on success
	 * @return arguments3 validator that takes arguments directly
	 * @since 0.16.0
	 */
	static <A1, A2, A3, X extends @Nullable Object> Arguments3Validator<A1, A2, A3, X> unwrap(
			Arguments1Validator<Arguments3<A1, A2, A3>, X> validator) {
		return ArgumentsValidators
			.derived(
					(a1, a2, a3, locale, constraintContext) -> validator.validate(Arguments.of(a1, a2, a3), locale,
							constraintContext),
					() -> Arguments3Validator.unwrap(validator.lazy()), validator::description);
	}

	/**
	 * Validates the arguments and returns the validated value or the accumulated
	 * violations.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the validated value or the constraint violations
	 */
	Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, Locale locale,
			ConstraintContext constraintContext);

	/**
	 * Returns a validator that takes a single {@link Arguments3} and validates the
	 * arguments it contains.
	 *
	 * <p>
	 * This is the inverse of {@link #unwrap}. A {@code null} container is rejected with a
	 * {@link NullPointerException} when the returned validator is applied.
	 * @return a validator that takes an Arguments3
	 * @since 0.16.0
	 */
	default Arguments1Validator<Arguments3<A1, A2, A3>, X> wrap() {
		return new Arguments1Validator<Arguments3<A1, A2, A3>, X>() {
			@Override
			public Validated<X> validate(@Nullable Arguments3<A1, A2, A3> args, Locale locale,
					ConstraintContext constraintContext) {
				final Arguments3<? extends A1, ? extends A2, ? extends A3> nonNullArgs = Objects.requireNonNull(args);
				return Arguments3Validator.this.validate(nonNullArgs.arg1(), nonNullArgs.arg2(), nonNullArgs.arg3(),
						locale, constraintContext);
			}

			@Override
			public Arguments1Validator<Arguments3<A1, A2, A3>, Supplier<X>> lazy() {
				return Arguments3Validator.this.lazy().wrap();
			}

			@Override
			public ValueDescription description() {
				return Arguments3Validator.this.description();
			}
		};
	}

	/**
	 * Returns a validator that maps the value produced on success with the given
	 * function. The function is not applied when validation fails.
	 * @param mapper the function applied to the validated value
	 * @param <X2> the type of the value produced after mapping
	 * @return a validator with the mapped result type
	 * @since 0.17.0
	 */
	default <X2 extends @Nullable Object> Arguments3Validator<A1, A2, A3, X2> map(
			Function<? super X, ? extends X2> mapper) {
		return ArgumentsValidators.derived(
				(a1, a2, a3, locale, constraintContext) -> this.validate(a1, a2, a3, locale, constraintContext)
					.map(mapper),
				() -> this.lazy()
					.map((Function<Supplier<X>, Supplier<X2>>) xSupplier -> () -> mapper.apply(xSupplier.get())),
				this::description);
	}

	/**
	 * Returns a validator that passes the value produced on success to the given
	 * validator.
	 *
	 * <p>
	 * If this validator fails, the given validator is not invoked and its violations are
	 * not collected.
	 * @param validator the validator applied to the validated value
	 * @param <X2> the type of the value produced by the given validator
	 * @return a chained validator
	 * @since 0.11.0
	 */
	default <X2 extends @Nullable Object> Arguments3Validator<A1, A2, A3, X2> andThen(
			ValueValidator<? super @NonNull X, ? extends X2> validator) {
		return ArgumentsValidators.derived(
				(a1, a2, a3, locale, constraintContext) -> this.validate(a1, a2, a3, locale, constraintContext)
					.flatMap(v -> validator.validate(v, locale, constraintContext)),
				() -> this.lazy()
					.andThen((xSupplier, locale, constraintContext) -> validator
						.validate(Objects.requireNonNull(xSupplier).get(), locale, constraintContext)
						.map(x2 -> () -> x2)),
				this::description);
	}

	/**
	 * Returns a validator that additionally checks the value produced by this validator
	 * with the given predicate. This is the place for a rule that spans several
	 * arguments, such as a password confirmation or a date range.
	 *
	 * <p>
	 * The predicate is evaluated only when this validator succeeds. If it returns
	 * {@code false}, a violation with the given name and message is reported; its last
	 * message argument is the produced value.
	 * @param predicate the rule that the produced value must satisfy
	 * @param name the name of the reported violation
	 * @param violationMessage the message key and the default message format of the
	 * reported violation
	 * @return a validator with the additional rule
	 * @since 0.18.0
	 */
	default Arguments3Validator<A1, A2, A3, X> constraintOnTarget(Predicate<? super X> predicate, String name,
			ViolationMessage violationMessage) {
		return ArgumentsValidators.derived(
				(a1, a2, a3, locale, constraintContext) -> this.validate(a1, a2, a3, locale, constraintContext)
					.flatMap(x -> ArgumentsValidators.constrained(x, predicate, name, violationMessage, locale)),
				() -> this.lazy()
					.andThen((xSupplier, locale, constraintContext) -> ArgumentsValidators
						.constrained(Objects.requireNonNull(xSupplier).get(), predicate, name, violationMessage, locale)
						.map(x -> () -> x)),
				this::description);
	}

	/**
	 * Returns a validator that converts its input with the given function before
	 * validating it.
	 *
	 * <p>
	 * The function is not validated; its result is passed to this validator. The new
	 * validator keeps the {@linkplain #description() description} of this validator: its
	 * input is the object that provides the arguments.
	 * @param mapper the function that converts the input of the new validator
	 * @param <A> the input type of the new validator
	 * @return a validator with the adapted input type
	 * @since 0.7.0
	 */
	default <A extends @Nullable Object> Arguments1Validator<A, X> compose(
			Function<@Nullable A, ? extends @Nullable Arguments3<? extends A1, ? extends A2, ? extends A3>> mapper) {
		return new Arguments1Validator<A, X>() {
			@Override
			public Validated<X> validate(@Nullable A a, Locale locale, ConstraintContext constraintContext) {
				final Arguments3<? extends A1, ? extends A2, ? extends A3> args = mapper.apply(a);
				return Arguments3Validator.this.validate(args.arg1(), args.arg2(), args.arg3(), locale,
						constraintContext);
			}

			@Override
			public Arguments1Validator<A, Supplier<X>> lazy() {
				return Arguments3Validator.this.lazy().compose(mapper);
			}

			@Override
			public ValueDescription description() {
				return Arguments3Validator.this.description();
			}
		};
	}

	/**
	 * Returns a description of the arguments that this validator expects.
	 *
	 * <p>
	 * A validator created by an {@code ArgumentsNValidatorBuilder} is described as
	 * {@link ValueDescription.Properties} with one property per argument. The default
	 * implementation returns {@link ValueDescription.Unknown}. {@link #map},
	 * {@link #andThen(ValueValidator)}, {@link #constraintOnTarget}, {@link #wrap} and
	 * {@link #compose} keep the description.
	 * @return the description of the arguments
	 * @since 0.18.0
	 * @see #describedAs(ValueDescription)
	 */
	default ValueDescription description() {
		return new ValueDescription.Unknown();
	}

	/**
	 * Returns a validator that validates like this validator and describes its arguments
	 * with the given description.
	 * @param description the description of the arguments
	 * @return a validator with the given description
	 * @since 0.18.0
	 * @see #description()
	 */
	default Arguments3Validator<A1, A2, A3, X> describedAs(ValueDescription description) {
		return ArgumentsValidators.derived(this, () -> this.lazy().describedAs(description), () -> description);
	}

	/**
	 * Returns a validator that produces a {@link Supplier} of the validated value.
	 *
	 * <p>
	 * The supplier is created only when validation succeeds; obtaining the value from it
	 * applies the mapper at that time. The default implementation throws
	 * {@link UnsupportedOperationException}; concrete validators override it.
	 * @return a validator that produces a supplier of the validated value
	 * @since 0.10.0
	 */
	default Arguments3Validator<A1, A2, A3, Supplier<X>> lazy() {
		throw new UnsupportedOperationException("lazy is not implemented!");
	}

	/**
	 * Validates the arguments with the default locale and
	 * {@link ConstraintGroup#DEFAULT}.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @return the validated value or the constraint violations
	 */
	default Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3) {
		return this.validate(a1, a2, a3, Locale.getDefault(), ConstraintGroup.DEFAULT);
	}

	/**
	 * Validates the arguments with the given constraint context and the default locale.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the validated value or the constraint violations
	 */
	default Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3,
			ConstraintContext constraintContext) {
		return this.validate(a1, a2, a3, Locale.getDefault(), constraintContext);
	}

	/**
	 * Validates the arguments with the given locale and {@link ConstraintGroup#DEFAULT}.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @return the validated value or the constraint violations
	 */
	default Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, Locale locale) {
		return this.validate(a1, a2, a3, locale, ConstraintGroup.DEFAULT);
	}

	/**
	 * Validates the arguments with the default locale and {@link ConstraintGroup#DEFAULT}
	 * and returns the validated value.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @return the validated value
	 * @throws ConstraintViolationsException if validation fails
	 */
	default X validated(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3) throws ConstraintViolationsException {
		return this.validate(a1, a2, a3).orElseThrow(ConstraintViolationsException::new);
	}

	/**
	 * Validates the arguments with the given constraint context and the default locale
	 * and returns the validated value.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the validated value
	 * @throws ConstraintViolationsException if validation fails
	 */
	default X validated(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, ConstraintContext constraintContext)
			throws ConstraintViolationsException {
		return this.validate(a1, a2, a3, constraintContext).orElseThrow(ConstraintViolationsException::new);
	}

	/**
	 * Validates the arguments with the given locale and {@link ConstraintGroup#DEFAULT}
	 * and returns the validated value.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @return the validated value
	 * @throws ConstraintViolationsException if validation fails
	 */
	default X validated(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, Locale locale)
			throws ConstraintViolationsException {
		return this.validate(a1, a2, a3, locale).orElseThrow(ConstraintViolationsException::new);
	}

	/**
	 * Validates the arguments with the given locale and constraint context and returns
	 * the validated value.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the validated value
	 * @throws ConstraintViolationsException if validation fails
	 */
	default X validated(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, Locale locale,
			ConstraintContext constraintContext) throws ConstraintViolationsException {
		return this.validate(a1, a2, a3, locale, constraintContext).orElseThrow(ConstraintViolationsException::new);
	}

}
