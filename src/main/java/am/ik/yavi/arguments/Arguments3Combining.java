package am.ik.yavi.arguments;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.Validated;
import am.ik.yavi.core.ValueValidator;
import am.ik.yavi.fn.Function3;
import am.ik.yavi.fn.Validations;
import java.util.Locale;
import java.util.function.Supplier;

/**
 * Combines 3 validators that validate the same input into a single validator.
 *
 * <p>
 * This is useful for cross-field validation: every validator receives the same input. The
 * validators are applied independently, all violations are accumulated, and the function
 * passed to {@link #apply} is applied only when every validation succeeds. Instances are
 * created with {@link ArgumentsValidators#combine} or by chaining {@code combine} on an
 * existing instance.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A> the type of the input validated by all validators
 * @param <R1> the type of the value produced by the validator at position 1
 * @param <R2> the type of the value produced by the validator at position 2
 * @param <R3> the type of the value produced by the validator at position 3
 * @since 0.7.0
 */
public class Arguments3Combining<A, R1, R2, R3> {

	/** The validator applied to the input at position 1. */
	protected final ValueValidator<? super A, ? extends R1> v1;

	/** The validator applied to the input at position 2. */
	protected final ValueValidator<? super A, ? extends R2> v2;

	/** The validator applied to the input at position 3. */
	protected final ValueValidator<? super A, ? extends R3> v3;

	/**
	 * Creates an instance with the given validators, which all receive the same input.
	 * @param v1 the validator applied to the input at position 1
	 * @param v2 the validator applied to the input at position 2
	 * @param v3 the validator applied to the input at position 3
	 */
	public Arguments3Combining(ValueValidator<? super A, ? extends R1> v1, ValueValidator<? super A, ? extends R2> v2,
			ValueValidator<? super A, ? extends R3> v3) {
		this.v1 = v1;
		this.v2 = v2;
		this.v3 = v3;
	}

	/**
	 * Returns a validator that applies every validator of this instance to the input and
	 * combines the validated values with the given function.
	 *
	 * <p>
	 * All violations are accumulated and the function is applied only when every
	 * validation succeeds.
	 * @param f the function that combines the validated values
	 * @param <X> the type of the value produced by the function
	 * @return a validator for the input
	 */
	public <X> Arguments1Validator<A, X> apply(Function3<? super R1, ? super R2, ? super R3, ? extends X> f) {
		return new Arguments1Validator<A, X>() {
			@Override
			public Validated<X> validate(A a, Locale locale, ConstraintContext constraintContext) {
				return Validations.apply(f::apply, Arguments3Combining.this.v1.validate(a, locale, constraintContext),
						Arguments3Combining.this.v2.validate(a, locale, constraintContext),
						Arguments3Combining.this.v3.validate(a, locale, constraintContext));
			}

			@Override
			public Arguments1Validator<A, Supplier<X>> lazy() {
				return (a, locale, constraintContext) -> Validations.apply((r1, r2, r3) -> () -> f.apply(r1, r2, r3),
						Arguments3Combining.this.v1.validate(a, locale, constraintContext),
						Arguments3Combining.this.v2.validate(a, locale, constraintContext),
						Arguments3Combining.this.v3.validate(a, locale, constraintContext));
			}
		};
	}

	/**
	 * Returns a new {@link Arguments4Combining} that additionally validates the input
	 * with the given validator.
	 * @param v4 the additional validator applied to the input
	 * @param <R4> the type of the value produced by the additional validator
	 * @return an arguments4 combining instance
	 */
	public <R4> Arguments4Combining<A, R1, R2, R3, R4> combine(ValueValidator<? super A, ? extends R4> v4) {
		return new Arguments4Combining<>(v1, v2, v3, v4);
	}

}
