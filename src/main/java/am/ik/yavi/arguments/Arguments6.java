package am.ik.yavi.arguments;

import am.ik.yavi.fn.Function6;
import org.jspecify.annotations.Nullable;

/**
 * An immutable container of 6 arguments.
 *
 * <p>
 * Instances are created with {@link Arguments#of} or with the constructor. The
 * {@code wrap()} and {@code unwrap(...)} methods of {@link Arguments6Validator} convert
 * between validating the arguments individually and validating this container as a single
 * value. This record only stores, compares and maps the argument values; it performs no
 * validation, and an argument may be {@code null}.
 *
 * <p>
 * As a record it is deconstructed by a record pattern, for example in a {@code switch}
 * over a {@link am.ik.yavi.core.Validated}: <pre>{@code
 * case Validated.Valid(Arguments6(var arg1, var arg2, var arg3, var arg4, var arg5, var arg6)) -> ...
 * }</pre>
 *
 * <p>
 * The {@code first*}, {@code last*}, {@code append}, {@code prepend} and {@code reverse}
 * methods derive another container from the same argument values.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <A3> the type of the argument at position 3
 * @param <A4> the type of the argument at position 4
 * @param <A5> the type of the argument at position 5
 * @param <A6> the type of the argument at position 6
 * @param arg1 the argument at position 1, possibly {@code null}
 * @param arg2 the argument at position 2, possibly {@code null}
 * @param arg3 the argument at position 3, possibly {@code null}
 * @param arg4 the argument at position 4, possibly {@code null}
 * @param arg5 the argument at position 5, possibly {@code null}
 * @param arg6 the argument at position 6, possibly {@code null}
 * @since 0.3.0
 */
public record Arguments6<A1, A2, A3, A4, A5, A6> (@Nullable A1 arg1, @Nullable A2 arg2, @Nullable A3 arg3,
		@Nullable A4 arg4, @Nullable A5 arg5, @Nullable A6 arg6) {

	/**
	 * Applies the given function to every argument contained in this container and
	 * returns its result.
	 *
	 * <p>
	 * No validation is performed and the arguments are passed as they are, possibly
	 * {@code null}.
	 * @param <X> the type of the result
	 * @param mapper the function to apply to the arguments
	 * @return the result of applying the mapper function to the arguments
	 */
	public <X> X map(
			Function6<? super A1, ? super A2, ? super A3, ? super A4, ? super A5, ? super A6, ? extends X> mapper) {
		return mapper.apply(arg1, arg2, arg3, arg4, arg5, arg6);
	}

	/**
	 * Returns a new {@link Arguments1} containing the arguments at positions 1 to 1 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments1 instance with arguments from arg1 to arg1
	 * @since 0.16.0
	 */
	public Arguments1<A1> first1() {
		return new Arguments1<>(arg1);
	}

	/**
	 * Returns a new {@link Arguments2} containing the arguments at positions 1 to 2 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments2 instance with arguments from arg1 to arg2
	 * @since 0.16.0
	 */
	public Arguments2<A1, A2> first2() {
		return new Arguments2<>(arg1, arg2);
	}

	/**
	 * Returns a new {@link Arguments3} containing the arguments at positions 1 to 3 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments3 instance with arguments from arg1 to arg3
	 * @since 0.16.0
	 */
	public Arguments3<A1, A2, A3> first3() {
		return new Arguments3<>(arg1, arg2, arg3);
	}

	/**
	 * Returns a new {@link Arguments4} containing the arguments at positions 1 to 4 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments4 instance with arguments from arg1 to arg4
	 * @since 0.16.0
	 */
	public Arguments4<A1, A2, A3, A4> first4() {
		return new Arguments4<>(arg1, arg2, arg3, arg4);
	}

	/**
	 * Returns a new {@link Arguments5} containing the arguments at positions 1 to 5 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments5 instance with arguments from arg1 to arg5
	 * @since 0.16.0
	 */
	public Arguments5<A1, A2, A3, A4, A5> first5() {
		return new Arguments5<>(arg1, arg2, arg3, arg4, arg5);
	}

	/**
	 * Returns a new {@link Arguments1} containing the arguments at positions 6 to 6 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments1 instance with arguments from arg6 to arg6
	 * @since 0.16.0
	 */
	public Arguments1<A6> last1() {
		return new Arguments1<>(arg6);
	}

	/**
	 * Returns a new {@link Arguments2} containing the arguments at positions 5 to 6 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments2 instance with arguments from arg5 to arg6
	 * @since 0.16.0
	 */
	public Arguments2<A5, A6> last2() {
		return new Arguments2<>(arg5, arg6);
	}

	/**
	 * Returns a new {@link Arguments3} containing the arguments at positions 4 to 6 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments3 instance with arguments from arg4 to arg6
	 * @since 0.16.0
	 */
	public Arguments3<A4, A5, A6> last3() {
		return new Arguments3<>(arg4, arg5, arg6);
	}

	/**
	 * Returns a new {@link Arguments4} containing the arguments at positions 3 to 6 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments4 instance with arguments from arg3 to arg6
	 * @since 0.16.0
	 */
	public Arguments4<A3, A4, A5, A6> last4() {
		return new Arguments4<>(arg3, arg4, arg5, arg6);
	}

	/**
	 * Returns a new {@link Arguments5} containing the arguments at positions 2 to 6 of
	 * this container.
	 *
	 * <p>
	 * The returned container holds the same argument values; no validation is performed.
	 * @return an Arguments5 instance with arguments from arg2 to arg6
	 * @since 0.16.0
	 */
	public Arguments5<A2, A3, A4, A5, A6> last5() {
		return new Arguments5<>(arg2, arg3, arg4, arg5, arg6);
	}

	/**
	 * Returns a new {@link Arguments7} with the given argument appended after the
	 * existing arguments.
	 *
	 * <p>
	 * The existing argument values are copied by reference; no validation is performed.
	 * @param <B> the type of the argument to append
	 * @param arg the argument to append, possibly {@code null}
	 * @return a new Arguments7 instance with the additional argument
	 * @since 0.16.0
	 */
	public <B> Arguments7<A1, A2, A3, A4, A5, A6, B> append(@Nullable B arg) {
		return new Arguments7<>(this.arg1, this.arg2, this.arg3, this.arg4, this.arg5, this.arg6, arg);
	}

	/**
	 * Returns a new {@link Arguments7} with the given argument prepended before the
	 * existing arguments.
	 *
	 * <p>
	 * The existing argument values are copied by reference; no validation is performed.
	 * @param <B> the type of the argument to prepend
	 * @param arg the argument to prepend, possibly {@code null}
	 * @return a new Arguments7 instance with the additional argument
	 * @since 0.16.0
	 */
	public <B> Arguments7<B, A1, A2, A3, A4, A5, A6> prepend(@Nullable B arg) {
		return new Arguments7<>(arg, this.arg1, this.arg2, this.arg3, this.arg4, this.arg5, this.arg6);
	}

	/**
	 * Returns a new {@link Arguments6} with the arguments in reverse order.
	 *
	 * <p>
	 * The argument values are copied by reference; no validation is performed.
	 * @return an Arguments6 instance with arguments in reverse order
	 * @since 0.16.0
	 */
	public Arguments6<A6, A5, A4, A3, A2, A1> reverse() {
		return new Arguments6<>(arg6, arg5, arg4, arg3, arg2, arg1);
	}

}
