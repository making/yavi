package am.ik.yavi.arguments;

import java.util.Locale;
import java.util.function.Supplier;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.Validated;

import am.ik.yavi.core.Validator;

import am.ik.yavi.fn.Function7;
import org.jspecify.annotations.Nullable;

/**
 * Default {@link Arguments7Validator} that applies a {@link Validator} to an
 * {@link Arguments7} container and maps the validated arguments with a {@link Function7}.
 *
 * <p>
 * The validator is applied applicatively, so all violations are accumulated, and the
 * mapper is applied only when validation succeeds. A {@code null} argument is accepted
 * unless the configured constraints reject it.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <A3> the type of the argument at position 3
 * @param <A4> the type of the argument at position 4
 * @param <A5> the type of the argument at position 5
 * @param <A6> the type of the argument at position 6
 * @param <A7> the type of the argument at position 7
 * @param <X> the type of the value produced when validation succeeds
 * @since 0.7.0
 */
public class DefaultArguments7Validator<A1, A2, A3, A4, A5, A6, A7, X>
		implements Arguments7Validator<A1, A2, A3, A4, A5, A6, A7, X> {

	/** The validator applied to the {@link Arguments7} container. */
	protected final Validator<Arguments7<A1, A2, A3, A4, A5, A6, A7>> validator;

	/** The mapper applied to the validated arguments. */
	protected final Function7<? super A1, ? super A2, ? super A3, ? super A4, ? super A5, ? super A6, ? super A7, ? extends X> mapper;

	/**
	 * Creates a validator that applies the given validator to an {@link Arguments7} built
	 * from the arguments and maps the validated arguments with the given function.
	 * @param validator the validator applied to the arguments
	 * @param mapper the mapper applied to the validated arguments
	 */
	public DefaultArguments7Validator(Validator<Arguments7<A1, A2, A3, A4, A5, A6, A7>> validator,
			Function7<? super A1, ? super A2, ? super A3, ? super A4, ? super A5, ? super A6, ? super A7, ? extends X> mapper) {
		this.validator = validator;
		this.mapper = mapper;
	}

	/**
	 * Returns a validator that produces a {@link Supplier} of the mapped value.
	 * @return a validator that produces a supplier of the validated value
	 * @since 0.10.0
	 */
	@Override
	public DefaultArguments7Validator<A1, A2, A3, A4, A5, A6, A7, Supplier<X>> lazy() {
		return new DefaultArguments7Validator<>(this.validator,
				(a1, a2, a3, a4, a5, a6, a7) -> () -> this.mapper.apply(a1, a2, a3, a4, a5, a6, a7));
	}

	/**
	 * Validates the arguments with the given validator and maps them with the configured
	 * mapper.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param a3 the argument at position 3, possibly {@code null}
	 * @param a4 the argument at position 4, possibly {@code null}
	 * @param a5 the argument at position 5, possibly {@code null}
	 * @param a6 the argument at position 6, possibly {@code null}
	 * @param a7 the argument at position 7, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the mapped value or the constraint violations
	 */
	@Override
	public Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, @Nullable A3 a3, @Nullable A4 a4, @Nullable A5 a5,
			@Nullable A6 a6, @Nullable A7 a7, Locale locale, ConstraintContext constraintContext) {
		return this.validator.applicative()
			.validate(Arguments.of(a1, a2, a3, a4, a5, a6, a7), locale, constraintContext)
			.map(values -> values.map(this.mapper));
	}

}
