package am.ik.yavi.arguments;

import java.util.Locale;
import java.util.function.Supplier;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.Validated;
import am.ik.yavi.core.Validator;
import am.ik.yavi.fn.Function2;
import am.ik.yavi.jsr305.Nullable;

/**
 * Default {@link Arguments2Validator} that applies a {@link Validator} to an
 * {@link Arguments2} container and maps the validated arguments with a {@link Function2}.
 *
 * <p>
 * The validator is applied applicatively, so all violations are accumulated, and the
 * mapper is applied only when validation succeeds. A {@code null} argument is accepted
 * unless the configured constraints reject it.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <A2> the type of the argument at position 2
 * @param <X> the type of the value produced when validation succeeds
 * @since 0.7.0
 */
public class DefaultArguments2Validator<A1, A2, X> implements Arguments2Validator<A1, A2, X> {

	/** The validator applied to the {@link Arguments2} container. */
	protected final Validator<Arguments2<A1, A2>> validator;

	/** The mapper applied to the validated arguments. */
	protected final Function2<? super A1, ? super A2, ? extends X> mapper;

	/**
	 * Creates a validator that applies the given validator to an {@link Arguments2} built
	 * from the arguments and maps the validated arguments with the given function.
	 * @param validator the validator applied to the arguments
	 * @param mapper the mapper applied to the validated arguments
	 */
	public DefaultArguments2Validator(Validator<Arguments2<A1, A2>> validator,
			Function2<? super A1, ? super A2, ? extends X> mapper) {
		this.validator = validator;
		this.mapper = mapper;
	}

	/**
	 * Returns a validator that produces a {@link Supplier} of the mapped value.
	 * @return a validator that produces a supplier of the validated value
	 * @since 0.10.0
	 */
	@Override
	public DefaultArguments2Validator<A1, A2, Supplier<X>> lazy() {
		return new DefaultArguments2Validator<>(this.validator, (a1, a2) -> () -> this.mapper.apply(a1, a2));
	}

	/**
	 * Validates the arguments with the given validator and maps them with the configured
	 * mapper.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param a2 the argument at position 2, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the mapped value or the constraint violations
	 */
	@Override
	public Validated<X> validate(@Nullable A1 a1, @Nullable A2 a2, Locale locale, ConstraintContext constraintContext) {
		return this.validator.applicative()
			.validate(Arguments.of(a1, a2), locale, constraintContext)
			.map(values -> values.map(this.mapper));
	}

}
