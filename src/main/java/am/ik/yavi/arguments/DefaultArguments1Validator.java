package am.ik.yavi.arguments;

import java.util.Locale;
import java.util.function.Supplier;

import am.ik.yavi.core.ConstraintContext;
import am.ik.yavi.core.Validated;
import am.ik.yavi.core.ValueDescription;
import am.ik.yavi.core.Validator;
import am.ik.yavi.fn.Function1;
import org.jspecify.annotations.Nullable;

/**
 * Default {@link Arguments1Validator} that applies a {@link Validator} to an
 * {@link Arguments1} container and maps the validated arguments with a {@link Function1}.
 *
 * <p>
 * The validator is applied applicatively, so all violations are accumulated, and the
 * mapper is applied only when validation succeeds. A {@code null} argument is accepted
 * unless the configured constraints reject it.
 *
 * Generated by https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> the type of the argument at position 1
 * @param <X> the type of the value produced when validation succeeds
 * @since 0.7.0
 */
public class DefaultArguments1Validator<A1, X> implements Arguments1Validator<A1, X> {

	/** The validator applied to the {@link Arguments1} container. */
	protected final Validator<Arguments1<A1>> validator;

	/** The mapper applied to the validated arguments. */
	protected final Function1<? super A1, ? extends X> mapper;

	private final Class<?> valueType;

	/**
	 * Creates a validator that applies the given validator to an {@link Arguments1} built
	 * from the arguments and maps the validated arguments with the given function.
	 * @param validator the validator applied to the arguments
	 * @param mapper the mapper applied to the validated arguments
	 */
	public DefaultArguments1Validator(Validator<Arguments1<A1>> validator, Function1<? super A1, ? extends X> mapper) {
		this(validator, mapper, Object.class);
	}

	/**
	 * Creates a validator like {@link #DefaultArguments1Validator(Validator, Function1)}
	 * that also knows the raw type of the argument, which is reported by
	 * {@link #description()}.
	 * @param validator the validator applied to the argument
	 * @param mapper the mapper applied to the validated argument
	 * @param valueType the raw type of the argument
	 * @since 0.18.0
	 */
	protected DefaultArguments1Validator(Validator<Arguments1<A1>> validator, Function1<? super A1, ? extends X> mapper,
			Class<?> valueType) {
		this.validator = validator;
		this.mapper = mapper;
		this.valueType = valueType;
	}

	/**
	 * Describes the argument as a {@link ValueDescription.Value} with its raw type and
	 * the constraints of the validator.
	 * @return the description of the argument
	 * @since 0.18.0
	 */
	@Override
	public ValueDescription description() {
		return ValueDescription.Value.of(this.valueType, this.validator);
	}

	/**
	 * Returns a validator that produces a {@link Supplier} of the mapped value.
	 * @return a validator that produces a supplier of the validated value
	 * @since 0.10.0
	 */
	@Override
	public DefaultArguments1Validator<A1, Supplier<X>> lazy() {
		return new DefaultArguments1Validator<>(this.validator, (a1) -> () -> this.mapper.apply(a1), this.valueType);
	}

	/**
	 * Validates the arguments with the given validator and maps them with the configured
	 * mapper.
	 * @param a1 the argument at position 1, possibly {@code null}
	 * @param locale the locale targeted for the violation messages
	 * @param constraintContext constraint context used by conditional constraints
	 * @return the mapped value or the constraint violations
	 */
	@Override
	public Validated<X> validate(@Nullable A1 a1, Locale locale, ConstraintContext constraintContext) {
		return this.validator.applicative()
			.validate(Arguments.of(a1), locale, constraintContext)
			.map(values -> values.map(this.mapper));
	}

}
