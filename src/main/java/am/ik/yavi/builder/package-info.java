/**
 * Builders for validators.
 *
 * <p>
 * {@link am.ik.yavi.builder.ValidatorBuilder} is the main entry point. It builds a
 * {@link am.ik.yavi.core.Validator} for a target type from property constraints, nested
 * validators, element validators for collections, maps and arrays, and conditional or
 * group-based validation:
 *
 * <pre>{@code
 * Validator<Person> validator = ValidatorBuilder.<Person>of()
 *     .constraint(Person::getName, "name", c -> c.notBlank().lessThanOrEqual(20))
 *     .constraint(Person::getAge, "age", c -> c.greaterThanOrEqual(0))
 *     .build();
 * }</pre>
 *
 * <p>
 * The typed builders, for example {@link am.ik.yavi.builder.StringValidatorBuilder} and
 * {@link am.ik.yavi.builder.IntegerValidatorBuilder}, implement
 * {@link am.ik.yavi.builder.ValueValidatorBuilder} and build a
 * {@link am.ik.yavi.core.ValueValidator} for a single value.
 * {@link am.ik.yavi.builder.YaviArguments} provides the same validators for use as
 * constructor or method arguments. The arguments builders
 * ({@link am.ik.yavi.builder.ArgumentsValidatorBuilder} and
 * {@code Arguments1ValidatorBuilder} through {@code Arguments16ValidatorBuilder}) build
 * validators that combine several argument validators.
 *
 * <p>
 * The typed and arguments builders are generated by {@code scripts/generate-args.sh}.
 * Validators are immutable and thread-safe; builders are mutable and meant to be used
 * from a single thread while building.
 *
 * @since 0.1.0
 */
