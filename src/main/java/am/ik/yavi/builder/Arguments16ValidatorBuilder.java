/**
 * Builds an {@link Arguments16Validator} by adding one validated argument at a time.
 *
 * <p>
 * Each {@code _xxx} method adds the next argument and returns the builder for the
 * following argument. The arguments are validated together, so every violation is
 * reported and the result is created only when all arguments are valid. The validator is
 * created with {@code apply} after all arguments have been added. Instances are obtained
 * from {@link YaviArguments} or from the builder of the previous argument count.
 *
 * <p>
 * The source of this class is generated by
 * https://github.com/making/yavi/blob/develop/scripts/generate-args.sh
 *
 * @param <A1> type of the first argument
 * @param <A2> type of argument at position 2
 * @param <A3> type of argument at position 3
 * @param <A4> type of argument at position 4
 * @param <A5> type of argument at position 5
 * @param <A6> type of argument at position 6
 * @param <A7> type of argument at position 7
 * @param <A8> type of argument at position 8
 * @param <A9> type of argument at position 9
 * @param <A10> type of argument at position 10
 * @param <A11> type of argument at position 11
 * @param <A12> type of argument at position 12
 * @param <A13> type of argument at position 13
 * @param <A14> type of argument at position 14
 * @param <A15> type of argument at position 15
 * @param <A16> type of argument at position 16
 * @param <R1> type of the validated value of the first argument
 * @param <R2> type of the validated value of argument at position 2
 * @param <R3> type of the validated value of argument at position 3
 * @param <R4> type of the validated value of argument at position 4
 * @param <R5> type of the validated value of argument at position 5
 * @param <R6> type of the validated value of argument at position 6
 * @param <R7> type of the validated value of argument at position 7
 * @param <R8> type of the validated value of argument at position 8
 * @param <R9> type of the validated value of argument at position 9
 * @param <R10> type of the validated value of argument at position 10
 * @param <R11> type of the validated value of argument at position 11
 * @param <R12> type of the validated value of argument at position 12
 * @param <R13> type of the validated value of argument at position 13
 * @param <R14> type of the validated value of argument at position 14
 * @param <R15> type of the validated value of argument at position 15
 * @param <R16> type of the validated value of argument at position 16
 * @since 0.14.0
 */
public final class Arguments16ValidatorBuilder<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, A13, A14, A15, A16, R1, R2, R3, R4, R5, R6, R7, R8, R9, R10, R11, R12, R13, R14, R15, R16> {

	final ValueValidator<A1, R1> v1;

	final ValueValidator<A2, R2> v2;

	final ValueValidator<A3, R3> v3;

	final ValueValidator<A4, R4> v4;

	final ValueValidator<A5, R5> v5;

	final ValueValidator<A6, R6> v6;

	final ValueValidator<A7, R7> v7;

	final ValueValidator<A8, R8> v8;

	final ValueValidator<A9, R9> v9;

	final ValueValidator<A10, R10> v10;

	final ValueValidator<A11, R11> v11;

	final ValueValidator<A12, R12> v12;

	final ValueValidator<A13, R13> v13;

	final ValueValidator<A14, R14> v14;

	final ValueValidator<A15, R15> v15;

	final ValueValidator<A16, R16> v16;

	/**
	 * Creates a builder from the value validators of the already added arguments.
	 * @param v1 value validator of the first argument
	 * @param v2 value validator of argument at position 2
	 * @param v3 value validator of argument at position 3
	 * @param v4 value validator of argument at position 4
	 * @param v5 value validator of argument at position 5
	 * @param v6 value validator of argument at position 6
	 * @param v7 value validator of argument at position 7
	 * @param v8 value validator of argument at position 8
	 * @param v9 value validator of argument at position 9
	 * @param v10 value validator of argument at position 10
	 * @param v11 value validator of argument at position 11
	 * @param v12 value validator of argument at position 12
	 * @param v13 value validator of argument at position 13
	 * @param v14 value validator of argument at position 14
	 * @param v15 value validator of argument at position 15
	 * @param v16 value validator of argument at position 16
	 * @since 0.14.0
	 */
	public Arguments16ValidatorBuilder(ValueValidator<A1, R1> v1, ValueValidator<A2, R2> v2, ValueValidator<A3, R3> v3,
			ValueValidator<A4, R4> v4, ValueValidator<A5, R5> v5, ValueValidator<A6, R6> v6, ValueValidator<A7, R7> v7,
			ValueValidator<A8, R8> v8, ValueValidator<A9, R9> v9, ValueValidator<A10, R10> v10,
			ValueValidator<A11, R11> v11, ValueValidator<A12, R12> v12, ValueValidator<A13, R13> v13,
			ValueValidator<A14, R14> v14, ValueValidator<A15, R15> v15, ValueValidator<A16, R16> v16) {
		this.v1 = v1;
		this.v2 = v2;
		this.v3 = v3;
		this.v4 = v4;
		this.v5 = v5;
		this.v6 = v6;
		this.v7 = v7;
		this.v8 = v8;
		this.v9 = v9;
		this.v10 = v10;
		this.v11 = v11;
		this.v12 = v12;
		this.v13 = v13;
		this.v14 = v14;
		this.v15 = v15;
		this.v16 = v16;
	}

	/**
	 * Builds an {@link Arguments16Validator} from the added arguments and the given
	 * function.
	 *
	 * <p>
	 * The function is applied only when all arguments are valid.
	 * @param <X> type of the result
	 * @param f function that creates the result from the validated values
	 * @return a new arguments validator
	 * @since 0.14.0
	 */
	public <X> Arguments16Validator<A1, A2, A3, A4, A5, A6, A7, A8, A9, A10, A11, A12, A13, A14, A15, A16, X> apply(
			Function16<? super R1, ? super R2, ? super R3, ? super R4, ? super R5, ? super R6, ? super R7, ? super R8, ? super R9, ? super R10, ? super R11, ? super R12, ? super R13, ? super R14, ? super R15, ? super R16, ? extends X> f) {
		return ArgumentsValidators
			.split(this.v1, this.v2, this.v3, this.v4, this.v5, this.v6, this.v7, this.v8, this.v9, this.v10, this.v11,
					this.v12, this.v13, this.v14, this.v15, this.v16)
			.apply(f);
	}

}
